export function formatBooklistsForAI(): string {
  const sections = BSPI_TECHNOLOGY_BOOKLISTS.map((tech) => {
    const semLines = SEMESTER_ORDER.map((sem) => {
      const subjects = tech.semesters[sem] ?? [];
      const subjList = subjects
        .map((s) => `${s.code} ${s.nameEn} (${s.nameBn})`)
        .join(', ');
      return `  - ${sem}: ${subjList}`;
    }).join('\n');

    return `${tech.department} [${tech.shortCode}, Code ${tech.techCode}] (${tech.nameBn}):\n${semLines}`;
  }).join('\n\n');

  return `
=== BTEB PROBIDHAN-2022 BOOKLISTS FOR BSPI's 6 TECHNOLOGIES ONLY ===
অফিশিয়াল রেফারেন্স: ${BTEB_BOOKLISTS_URL}
${sections}
=== END OF PROBIDHAN-2022 BOOKLISTS ===
`.trim();
}
